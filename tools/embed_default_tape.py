#!/usr/bin/env python3
"""
tools/embed_default_tape.py -- regenerate host/tape.html's embedded DEFAULT_TAPE.

The viewer is a single offline HTML file, so it carries a copy of the
committed evidence tape so that opening it with no arguments still shows a
real run. That copy must not drift from `host/suite_tape.csv`, which is
regenerated by `make check`. This script rewrites the embedded array in
place from the CSV, so the two can never disagree by accident.

Usage:
    python3 tools/embed_default_tape.py [--check]

    (no --check)  rewrite host/tape.html from host/suite_tape.csv
    --check       exit non-zero if host/tape.html is out of sync with the CSV
"""

import json
import os
import re
import sys

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CSV_PATH = os.path.join(REPO_ROOT, "host", "suite_tape.csv")
HTML_PATH = os.path.join(REPO_ROOT, "host", "tape.html")

MODE_NAMES = {0: "HP", 1: "HOLD", 2: "HOME"}


def load_rows():
    rows = []
    with open(CSV_PATH, "r", encoding="utf-8") as f:
        header = f.readline().strip().split(",")
        idx = {name: i for i, name in enumerate(header)}
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split(",")
            if len(parts) < len(header):
                continue
            try:
                tick = int(parts[idx["tick"]])
                cycles_in = int(parts[idx["cycles_in"]])
                cycles_out = int(parts[idx["cycles_out"]])
                latency = int(parts[idx["latency_cycles"]])
                seq = int(parts[idx["seq"]])
                u = int(parts[idx["u_proposed"]])
                theta = int(parts[idx["theta_applied"]])
                mode = int(parts[idx["mode"]])
                faults = int(parts[idx["fault_bits"]], 16) \
                    if parts[idx["fault_bits"]].lower().startswith("0x") \
                    else int(parts[idx["fault_bits"]])
            except (KeyError, ValueError):
                continue
            rows.append({
                "tick": tick,
                "cycles_in": cycles_in,
                "cycles_out": cycles_out,
                "latency_cycles": latency,
                "seq": seq,
                "u_proposed": u,
                "theta_applied": theta,
                "mode": mode,
                "mode_name": MODE_NAMES.get(mode, "UNK"),
                "fault_bits": faults,
                "fault_hex": "0x%04X" % faults,
            })
    return rows


def render(rows):
    return json.dumps(rows, separators=(", ", ": "))


def main():
    check_only = "--check" in sys.argv
    if not os.path.isfile(CSV_PATH):
        print("error: %s not found -- run `make -C qnx check` first" % CSV_PATH)
        return 1
    if not os.path.isfile(HTML_PATH):
        print("error: %s not found" % HTML_PATH)
        return 1

    rows = load_rows()
    if not rows:
        print("error: no usable rows in %s" % CSV_PATH)
        return 1
    payload = render(rows)

    with open(HTML_PATH, "r", encoding="utf-8") as f:
        html = f.read()

    pattern = re.compile(r"(const\s+DEFAULT_TAPE\s*=\s*)(\[.*?\])\s*;", re.S)
    m = pattern.search(html)
    if not m:
        print("error: could not find the DEFAULT_TAPE array in %s" % HTML_PATH)
        return 1

    if check_only:
        if m.group(2) == payload:
            print("[TAPE PASS] host/tape.html DEFAULT_TAPE is in sync with host/suite_tape.csv "
                  "(%d rows)" % len(rows))
            return 0
        print("[TAPE ERROR] host/tape.html DEFAULT_TAPE is OUT OF SYNC with "
              "host/suite_tape.csv -- run `python3 tools/embed_default_tape.py`")
        return 1

    html_new = html[:m.start(2)] + payload + html[m.end(2):]
    with open(HTML_PATH, "w", encoding="utf-8") as f:
        f.write(html_new)
    print("[TAPE] embedded %d rows from host/suite_tape.csv into host/tape.html" % len(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
